"""tests/mcp_servers/file/test_file_server_audit_records.py

Shared audit-record coverage for POST /v1/call_tool on the file-write and file-delete
servers (REQ-001, REQ-002).

Each server must emit exactly one structured audit record on every path it can take:
accepted dispatch, the disabled-allowed_dirs early return, and the validate_args early
return. Records are captured by replacing the server module's `logger` with a MagicMock,
so the real emission path (`_audit_log` and `_build_audit_record`) is exercised rather
than stubbed out. The service singleton is replaced with a stand-in that only exposes
`get_dispatch_table`, so no filesystem write or delete happens.
"""

from __future__ import annotations

import dataclasses
import json
from typing import Any
from unittest.mock import AsyncMock, MagicMock

import pytest
from fastapi.testclient import TestClient
from mcp_servers import models

from tests.mcp_servers._auth_headers import MCP_TEST_AUTH_HEADERS

SESSION_ID = "sess-audit-0001"
REQUEST_ID = "req-audit-0001"
LONG_PATH = "/tmp/" + "a" * 100


class _FakeService:
    """Stand-in for the write/delete service, exposing only get_dispatch_table."""

    def __init__(self, tool_names: list[str], handler: AsyncMock) -> None:
        self._table: dict[str, Any] = {name: handler for name in tool_names}

    def get_dispatch_table(self) -> dict[str, Any]:
        return self._table


def _tool_names(module: Any) -> list[str]:
    return [tool["name"] for tool in module.TOOL_LIST]


def _capture_logger(monkeypatch: pytest.MonkeyPatch, module: Any) -> MagicMock:
    """Replace the server module's logger so emitted records can be read back."""
    fake = MagicMock()
    monkeypatch.setattr(module, "logger", fake)
    return fake


def _audit_records(logger: MagicMock) -> list[dict[str, Any]]:
    """Parse every record the module logger emitted at info level.

    A non-JSON info call raises here, which is the intended failure: the call_tool
    path must emit the audit record and nothing else.
    """
    return [json.loads(call.args[0]) for call in logger.info.call_args_list]


def _post(
    module: Any,
    body: dict[str, Any],
    idempotency_key: str,
) -> Any:
    client = TestClient(module.app, headers=MCP_TEST_AUTH_HEADERS)
    return client.post(
        "/v1/call_tool",
        json=body,
        headers={
            "x-session-id": SESSION_ID,
            "x-request-id": REQUEST_ID,
            "x-idempotency-key": idempotency_key,
        },
    )


def _assert_record_shape(
    record: dict[str, Any],
    *,
    tool: str,
    server_key: str,
    target: str,
    outcome: str,
    request_id: str,
) -> None:
    """Assert the shared field shape every file-server audit record must carry.

    `session_id` is read from the x-session-id header. `request_id` is generated by the
    auth middleware and stored on request.state, so it is compared with the X-Request-Id
    response header rather than with the sent x-request-id header: state wins over the
    header fallback in extract_request_context.
    """
    assert record["event"] == "mcp_tool_exec"
    assert record["source"] == "mcp_server"
    assert record["tool"] == tool
    assert record["server_key"] == server_key
    assert record["target"] == target
    assert record["outcome"] == outcome
    assert record["session_id"] == SESSION_ID
    assert record["request_id"] == request_id
    assert isinstance(record["ts"], float)


def _reject_args(tool_name: str, args: dict[str, object]) -> None:
    """Stand in for a registered tool validator that rejects the arguments."""
    raise ValueError("path is required")


class TestFileWriteAuditRecords:
    def test_accepted_call_emits_one_ok_record(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        from mcp_servers.file import write_server

        handler = AsyncMock(return_value="wrote 1 byte")
        monkeypatch.setattr(
            write_server, "_service", _FakeService(_tool_names(write_server), handler)
        )
        logger = _capture_logger(monkeypatch, write_server)

        resp = _post(
            write_server,
            {
                "name": "write_file",
                "args": {"path": LONG_PATH, "content": "secret-body"},
            },
            "idem-audit-write-ok",
        )
        assert resp.status_code == 200
        assert resp.json()["is_error"] is False

        records = _audit_records(logger)
        assert len(records) == 1
        _assert_record_shape(
            records[0],
            tool="write_file",
            server_key="file_write",
            target=LONG_PATH[:80],
            outcome="ok",
            request_id=resp.headers["X-Request-Id"],
        )
        assert "secret-body" not in json.dumps(records[0])

    def test_disabled_allowed_dirs_emits_rejected_record(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        from mcp_servers.file import write_server

        monkeypatch.setattr(
            write_server,
            "_cfg",
            dataclasses.replace(write_server._cfg, allowed_dirs=[]),
        )
        handler = AsyncMock(return_value="must not run")
        monkeypatch.setattr(
            write_server, "_service", _FakeService(_tool_names(write_server), handler)
        )
        logger = _capture_logger(monkeypatch, write_server)

        resp = _post(
            write_server,
            {
                "name": "write_file",
                "args": {"path": "/tmp/audit-case.txt", "content": "x"},
            },
            "idem-audit-write-disabled",
        )
        assert resp.status_code == 200
        body = resp.json()
        assert body["is_error"] is True
        assert body["result"] == "Tool disabled: allowed_dirs is empty"

        records = _audit_records(logger)
        assert len(records) == 1
        _assert_record_shape(
            records[0],
            tool="write_file",
            server_key="file_write",
            target="/tmp/audit-case.txt",
            outcome="rejected",
            request_id=resp.headers["X-Request-Id"],
        )
        handler.assert_not_awaited()

    def test_validation_error_emits_rejected_record(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        from mcp_servers.file import write_server

        # No validator is registered for write_file, so the validator seam is driven
        # directly to exercise the server's validate_args early return.
        monkeypatch.setattr(models, "validate_tool_args", _reject_args)
        handler = AsyncMock(return_value="must not run")
        monkeypatch.setattr(
            write_server, "_service", _FakeService(_tool_names(write_server), handler)
        )
        logger = _capture_logger(monkeypatch, write_server)

        resp = _post(
            write_server, {"name": "write_file", "args": {}}, "idem-audit-write-bad"
        )
        assert resp.status_code == 200
        body = resp.json()
        assert body["is_error"] is True
        assert body["result"].startswith("Validation error:")

        records = _audit_records(logger)
        assert len(records) == 1
        _assert_record_shape(
            records[0],
            tool="write_file",
            server_key="file_write",
            target="",
            outcome="rejected",
            request_id=resp.headers["X-Request-Id"],
        )
        handler.assert_not_awaited()


