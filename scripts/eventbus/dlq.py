_dlq_file_write_failure_counter = Counter(
    "eventbus_dlq_file_write_failure_total",
    "Number of DLQ file write failures",
)

_dlq_outbox_generated_counter = Counter(
    "eventbus_dlq_outbox_generated_total",
    "Number of DLQ files generated by the outbox worker",
)

_dlq_outbox_attempt_failure_counter = Counter(
    "eventbus_dlq_outbox_attempt_failure_total",
    "Number of failed DLQ outbox generation attempts",
)

_dlq_outbox_failed_counter = Counter(
    "eventbus_dlq_outbox_failed_total",
    "Number of DLQ outbox rows that reached the terminal failed state",
)


@dataclass(frozen=True)
class DlqEventRecord:
    """A single event record written to the dead-letter queue as a JSON file on disk."""

    seq: int
    event_id: str
    topic: str
    payload: dict | list | str | int | float | bool
    producer: str
    published_at: str
    dlq_at: str
    consumer_delivery_failure_count: int | None = (
        None  # REQ-002: per-consumer failure count
    )


def _build_dlq_record(
    row: sqlite3.Row,
    now: str,
    consumer_delivery_failure_count: int | None = None,
) -> DlqEventRecord:
    """Construct a DlqEventRecord from a SQLite row and current timestamp."""
    return DlqEventRecord(
        seq=row["seq"],
        event_id=row["event_id"],
        topic=row["topic"],
        payload=orjson.loads(row["payload"]),
        producer=row["producer"],
        published_at=row["published_at"],
        dlq_at=now,
        consumer_delivery_failure_count=consumer_delivery_failure_count,
    )


# ADR-006 INV-13: an event is promotable only when every consumer that has a delivery
# record for it (created by that consumer's ACK or NACK) has exhausted its retry
# budget and none of them has ACKed. One parameter: the retry limit. Shared by the
# sweep query and is_promotable() so the two paths cannot drift apart.
_PROMOTABLE_CONDITION = (
    "EXISTS (SELECT 1 FROM consumer_delivery cd WHERE cd.event_id = e.event_id)"
    " AND NOT EXISTS (SELECT 1 FROM consumer_delivery cd"
    " WHERE cd.event_id = e.event_id"
    " AND (cd.acked = 1 OR cd.consumer_delivery_failure_count < ?))"
)


def is_promotable(db: sqlite3.Connection, event_id: str, max_retry: int) -> bool:
    """Return True if the event is not yet in the DLQ and meets the promotion rule.

    ADR-006 INV-13: every consumer with a delivery record for the event has reached
    ``max_retry`` and none has ACKed. An event with no delivery record is never
    promotable.
    """
    row = db.execute(
        "SELECT 1 FROM events e WHERE e.event_id = ? AND e.dlq_at IS NULL AND "  # nosec B608 — constant SQL fragment, values parameterized
        + _PROMOTABLE_CONDITION,
        (event_id, max_retry),
    ).fetchone()
    return row is not None


def _shared_promote(db: sqlite3.Connection, deadletter_dir: str, max_retry: int) -> int:
    """Shared promotion logic for the sweep path. DB-only since dlqbox001 (REQ-003).

    REQ-002 and ADR-006 INV-13: promotes events where every consumer with a delivery
    record has reached the retry threshold and none has ACKed. Each promotion commits
    the dlq_at stamp together with its dlq_outbox request row in one transaction; the
    rowcount guard means a racing promotion never duplicates the request row. File
    generation belongs to the outbox worker (process_outbox), never to this path.

    The deadletter_dir parameter is kept for call-site signature stability; the
    promotion path itself does not touch the filesystem.
    """
    now = now_iso()
    rows = db.execute(
        "SELECT e.event_id"  # nosec B608 — constant SQL fragment, values parameterized
        " FROM events e"
        " WHERE e.dlq_at IS NULL AND " + _PROMOTABLE_CONDITION,
        (max_retry,),
    ).fetchall()

    promoted = 0
    for row in rows:
        event_id = row["event_id"]
        cur = db.execute(
            "UPDATE events SET dlq_at = ? WHERE event_id = ? AND dlq_at IS NULL",
            (now, event_id),
        )
        if cur.rowcount == 1:
            insert_outbox_row(db, event_id, now)
        db.commit()
        if cur.rowcount:
            promoted += 1

    return promoted


def _shared_promote_single(
    db: sqlite3.Connection,
    deadletter_dir: str,
    event_id: str,
    consumer_failure_count: int | None = None,
) -> bool:
    """Shared promotion logic for single inline promotion. DB-only since dlqbox001.

    Commits the dlq_at stamp and the dlq_outbox request row in one transaction; the
    rowcount guard means a racing promotion never duplicates the request row and the
    return value stays True only when this call newly promoted (rowcount > 0).
    File generation belongs to the outbox worker (process_outbox), never to this path.

    Args:
        db: Database connection.
        deadletter_dir: Kept for call-site signature stability; unused here.
        event_id: Event identifier.
        consumer_failure_count: Per-consumer failure count (REQ-002), logged only.
    """
    now = now_iso()
    cur = db.execute(
        "UPDATE events SET dlq_at = ? WHERE event_id = ? AND dlq_at IS NULL",
        (now, event_id),
    )
    if cur.rowcount == 1:
        insert_outbox_row(db, event_id, now)
    db.commit()
    if cur.rowcount:
        logger.warning(
            "dlq inline promoted event_id=%s consumer_delivery_failure_count=%s",
            event_id,
            consumer_failure_count,
        )
    return cur.rowcount > 0


def sweep_orphans(
    db: sqlite3.Connection,
    deadletter_dir: str,
    max_retry: int,
) -> int:
    """Sweep events that meet the promotion rule but were not promoted inline.

    This is the self-healing repair path: it promotes events that inline promotion
    left live, for example after a crash between the promotion commit and a later
    step. A non-zero return value is expected after such a failure and is logged by
    the caller. Promotion is a DB-only transaction (dlqbox001): a promoted event
    always carries its dlq_outbox request row in the same commit, so the sweep also
    re-drives generation for events whose artifact was never generated.
    """
    return _shared_promote(db, deadletter_dir, max_retry)


def reconcile_missing_dlq_files(
    db: sqlite3.Connection,
    deadletter_dir: str,
) -> dict[str, int]:
    """Detect and rebuild lost DLQ files, and classify outbox inconsistencies.

    REQ-001, REQ-002, REQ-003: lists promoted events (dlq_at IS NOT NULL) whose
    {event_id}.json file is absent and rebuilds each through _atomic_write, reusing
    the sweep's failure metering. Lock-free by design: the caller holds
    run_with_db_lock, exactly as it does for sweep_orphans. Idempotent — an existing
    file is never rewritten.

    dlqbox001 (REQ-007) adds three report-only classifications: ``orphans`` —
    *.json files directly in deadletter_dir (the requeued/ subdirectory used by
    archive_dlq_record is not scanned) whose event_id has neither a promoted event
    row nor a done dlq_outbox row; ``interrupted_tmp`` — lingering .dlq_tmp_*
    leftovers from interrupted atomic writes (counted, never deleted here);
    ``mismatch`` — promoted events whose existing file does not match the canonical
    fields rebuilt from the database (counted, never silently rewritten).

    Returns {checked, rebuilt, failed, orphans, interrupted_tmp, mismatch}.
    """
    checked = rebuilt = failed = mismatch = 0
    rows = db.execute(
        "SELECT e.seq, e.event_id, e.topic, e.payload, e.producer,"  # nosec B608 — constant SQL fragment, values parameterized
        " e.published_at, e.dlq_at"
        " FROM events e"
        " WHERE e.dlq_at IS NOT NULL"
        " AND NOT EXISTS (SELECT 1 FROM events d WHERE d.redelivered_from = e.event_id)"
    ).fetchall()

    for row in rows:
        checked += 1
        event_id = row["event_id"]
        dst = Path(deadletter_dir) / f"{event_id}.json"
        if dst.exists():
            if _existing_file_mismatches(dst, row):
                mismatch += 1
            continue
        consumer_row = db.execute(
            f"SELECT MAX({_COL_CONSUMER_DELIVERY_FAILURE_COUNT}) FROM consumer_delivery "  # nosec B608 — column names are module-level constants, values parameterized
            "WHERE event_id = ?",
            (event_id,),
        ).fetchone()
        failure_count = (
            int(consumer_row[0]) if consumer_row and consumer_row[0] else None
        )
        record = DlqEventRecord(
            seq=row["seq"],
            event_id=event_id,
            topic=row["topic"],
            payload=orjson.loads(row["payload"]),
            producer=row["producer"],
            published_at=row["published_at"],
            dlq_at=row["dlq_at"],
            consumer_delivery_failure_count=failure_count,
        )
        try:
            _atomic_write(deadletter_dir, event_id, record)
        except OSError:
            _dlq_file_write_failure_counter.inc()
            logger.exception(
                "dlq reconcile: DLQ file write failed event_id=%s", event_id
            )
            failed += 1
            continue
        rebuilt += 1

    return {
        "checked": checked,
        "rebuilt": rebuilt,
        "failed": failed,
        "orphans": _count_orphan_dlq_files(db, deadletter_dir),
        "interrupted_tmp": sum(1 for _ in Path(deadletter_dir).glob(".dlq_tmp_*")),
        "mismatch": mismatch,
    }


def _existing_file_mismatches(dst: Path, row: sqlite3.Row) -> bool:
    """True when an existing DLQ file differs from the canonical DB state (REQ-007).

    Compares seq, event_id, topic, payload, producer, published_at and dlq_at. A
    file that does not parse as a canonical JSON object is also a mismatch: it
    cannot be confirmed equivalent. consumer_delivery_failure_count is excluded —
    the delivery table can age after promotion.
    """
    try:
        data = orjson.loads(dst.read_bytes())
    except (orjson.JSONDecodeError, UnicodeDecodeError):
        return True
    if not isinstance(data, dict):
        return True
    return bool(
        data.get("seq") != row["seq"]
        or data.get("event_id") != row["event_id"]
        or data.get("topic") != row["topic"]
        or data.get("payload") != orjson.loads(row["payload"])
        or data.get("producer") != row["producer"]
        or data.get("published_at") != row["published_at"]
        or data.get("dlq_at") != row["dlq_at"]
    )


def _count_orphan_dlq_files(db: sqlite3.Connection, deadletter_dir: str) -> int:
    """Count DLQ files with no promoted event row and no done outbox row (REQ-007).

    Report-only: orphan files are never deleted here. The requeued/ subdirectory is
    not scanned — only *.json files directly in deadletter_dir are candidates.
    """
    done_ids = done_outbox_event_ids(db)
    orphans = 0
    for path in Path(deadletter_dir).glob("*.json"):
        event_id = path.stem
        if event_id in done_ids:
            continue
        promoted = db.execute(
            "SELECT 1 FROM events WHERE event_id = ? AND dlq_at IS NOT NULL",
            (event_id,),
        ).fetchone()
        if promoted is None:
            orphans += 1
    return orphans


def promote_single(
    db: sqlite3.Connection,
    deadletter_dir: str,
    event_id: str,
    consumer_failure_count: int | None = None,
) -> bool:
    """Promote one event to DLQ immediately (inline on nack threshold).

    Returns True if promoted, False if already in DLQ or not found.
    DB-only since dlqbox001 (REQ-003): the dlq_at stamp and the dlq_outbox request
    row commit in one transaction, and the artifact is generated durably by the
    outbox worker (process_outbox) — this call never touches the filesystem.

    Args:
        db: Database connection.
        deadletter_dir: Kept for call-site signature stability; unused here.
        event_id: Event identifier.
        consumer_failure_count: Per-consumer failure count (REQ-002).
    """
    return _shared_promote_single(db, deadletter_dir, event_id, consumer_failure_count)


def _atomic_write(deadletter_dir: str, event_id: str, record: DlqEventRecord) -> None:
    """Atomically write a dead-letter queue event record to disk via temp file + rename."""
    dir_path = Path(deadletter_dir)
    dir_path.mkdir(parents=True, exist_ok=True)
    dst = dir_path / f"{event_id}.json"
    fd, tmp_path = tempfile.mkstemp(dir=dir_path, prefix=".dlq_tmp_")
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(orjson.dumps(record))
        os.replace(tmp_path, dst)
    except (OSError, TypeError):
        try:
            os.unlink(tmp_path)
        except OSError:
            pass
        raise


# -- Outbox worker (dlqbox001) ------------------------------------------------


def _iso_after(seconds: float) -> str:
    """Return a now_iso()-format timestamp the given number of seconds from now.

    Same second-precision UTC 'Z' format as now_iso(), so next_attempt_at stays
    lexicographically comparable with the timestamps it is compared against.
    """
    return (datetime.now(UTC) + timedelta(seconds=seconds)).strftime(
        "%Y-%m-%dT%H:%M:%SZ"
    )


def _canonical_record_bytes(record: DlqEventRecord) -> bytes:
    """Render the canonical JSON bytes of a DlqEventRecord.

    The same orjson.dumps call _atomic_write writes, so an existing file written by
    any generator path can be compared byte-for-byte for the idempotence check.
    """
    return orjson.dumps(record)


def _rebuild_event_record(
    db: sqlite3.Connection, event_id: str
) -> DlqEventRecord | None:
    """Rebuild the DlqEventRecord of one promoted event (reconcile query shape).

    consumer_delivery_failure_count is the MAX across consumers computed at
    generation time — the worker never sees the inline NACK-time count. Returns
    None when the event row is absent or not promoted.
    """
    row = db.execute(
        "SELECT e.seq, e.event_id, e.topic, e.payload, e.producer,"  # nosec B608 — constant SQL fragment, values parameterized
        " e.published_at, e.dlq_at"
        " FROM events e WHERE e.event_id = ? AND e.dlq_at IS NOT NULL",
        (event_id,),
    ).fetchone()
    if row is None:
        return None
    consumer_row = db.execute(
        f"SELECT MAX({_COL_CONSUMER_DELIVERY_FAILURE_COUNT}) FROM consumer_delivery "  # nosec B608 — column names are module-level constants, values parameterized
        "WHERE event_id = ?",
        (event_id,),
    ).fetchone()
    failure_count = int(consumer_row[0]) if consumer_row and consumer_row[0] else None
    return DlqEventRecord(
        seq=row["seq"],
        event_id=row["event_id"],
        topic=row["topic"],
        payload=orjson.loads(row["payload"]),
        producer=row["producer"],
        published_at=row["published_at"],
        dlq_at=row["dlq_at"],
        consumer_delivery_failure_count=failure_count,
    )


async def _register_failed_attempt(
    db: sqlite3.Connection,
    event_id: str,
    attempts: int,
    cfg: EventBusConfig,
    error_text: str,
    run_locked: Callable[[Any], Awaitable[Any]],
) -> bool:
    """Persist one failed outbox generation attempt; return True when the row is terminal.

    attempts+1, last_error=error_text, and next_attempt_at = now +
    min(base * 2**(attempt-1), cap_seconds) with base/cap from cfg (REQ-005).
    When the new attempt count reaches cfg.outbox_max_attempts the row becomes
    'failed' and is never fetched again. The write runs in its own locked
    transaction; a DB error there propagates to the cycle caller and the row
    stays pending for the next cycle (REQ-006).
    """
    new_attempts = attempts + 1
    terminal = new_attempts >= cfg.outbox_max_attempts
    delay = min(
        cfg.outbox_backoff_base_seconds * 2 ** (new_attempts - 1),
        cfg.outbox_backoff_max_seconds,
    )
    _dlq_outbox_attempt_failure_counter.inc()
    if terminal:
        _dlq_outbox_failed_counter.inc()

    def _write() -> None:
        record_attempt_failure(db, event_id, error_text, _iso_after(delay), terminal)
        db.commit()

    await run_locked(_write)
    return terminal


def _complete_outbox_row(db: sqlite3.Connection, event_id: str) -> None:
    """Locked completion write: mark the outbox row done and commit (REQ-004)."""
    mark_done(db, event_id, now_iso())
    db.commit()


async def process_outbox(
    db: sqlite3.Connection,
    deadletter_dir: str,
    cfg: EventBusConfig,
    run_locked: Callable[[Any], Awaitable[Any]],
) -> dict[str, int]:
    """Consume due dlq_outbox rows and durably generate their DLQ artifacts.

    REQ-004: called once per dlq_loop cycle; a pending row is simply due again on
    the next cycle after a crash or restart (REQ-006). REQ-005: a failing artifact
    records a bounded, persisted attempt (exponential backoff, terminal 'failed' at
    cfg.outbox_max_attempts) and never aborts the loop — per-event isolation.
    A destination file that already holds byte-identical canonical content is
    accepted without rewrite (idempotence). DB reads and completion writes each run
    in their own locked transaction via run_locked (route_helpers.run_with_db_lock
    injected by the caller); _atomic_write runs outside any lock hold. The worker
    never mutates events: dlq_at is written only by the promotion paths.

    Returns {processed, generated, failed_attempts, terminal_failed} counts.
    """
    now = now_iso()
    rows = await run_locked(lambda: fetch_due_pending(db, now))
    report = {"processed": 0, "generated": 0, "failed_attempts": 0, "terminal_failed": 0}

    for row in rows:
        event_id = str(row["event_id"])
        attempts = int(row["attempts"])
        report["processed"] += 1

        record = await run_locked(
            lambda event_id=event_id: _rebuild_event_record(db, event_id)
        )
        if record is None:
            # FK guarantees this event_id existed at insert time; a missing row is
            # defensive-only. Record a bounded failed attempt and continue (REQ-005).
            logger.error("dlq outbox: event row missing event_id=%s", event_id)
            report["failed_attempts"] += 1
            if await _register_failed_attempt(
                db, event_id, attempts, cfg, "dlq event row missing", run_locked
            ):
                report["terminal_failed"] += 1
            continue

        canonical = _canonical_record_bytes(record)
        dst = Path(deadletter_dir) / f"{event_id}.json"
        try:
            if dst.exists() and dst.read_bytes() == canonical:
                # Idempotence: the artifact is already canonical — complete without rewrite.
                await run_locked(
                    lambda event_id=event_id: _complete_outbox_row(db, event_id)
                )
                continue
            _atomic_write(deadletter_dir, event_id, record)
        except OSError as exc:
            _dlq_file_write_failure_counter.inc()
            logger.exception(
                "dlq outbox: artifact generation failed event_id=%s attempts=%d",
                event_id,
                attempts + 1,
            )
            report["failed_attempts"] += 1
            if await _register_failed_attempt(
                db, event_id, attempts, cfg, str(exc), run_locked
            ):
                report["terminal_failed"] += 1
            continue

        await run_locked(lambda event_id=event_id: _complete_outbox_row(db, event_id))
        _dlq_outbox_generated_counter.inc()
        report["generated"] += 1

    return report


def archive_dlq_record(deadletter_dir: str, event_id: str) -> bool:
    """Move {deadletter_dir}/{event_id}.json to {deadletter_dir}/requeued/{event_id}_{timestamp}.json.

    Creates the requeued/ subdirectory if it doesn't exist. Uses os.replace() for atomic move.
    Returns True if the file was moved, False if the source file didn't exist.
    """
    src_dir = Path(deadletter_dir)
    src_file = src_dir / f"{event_id}.json"
    if not src_file.exists():
        return False

    requeued_dir = src_dir / "requeued"
    requeued_dir.mkdir(parents=True, exist_ok=True)

    timestamp = now_iso().replace(":", "-").replace(".", "-")
    dst_file = requeued_dir / f"{event_id}_{timestamp}.json"

    try:
        os.replace(str(src_file), str(dst_file))
        return True
    except OSError:
        return False
