#!/usr/bin/env python3
"""scripts/rag/ingestion/ingester.py

Reads rag-src/chunk/*.json (JSON files generated by ChunkSplitter.py),
generates embeddings, and ingests them into SQLite (documents / chunks / chunks_vec).
Processed files are moved to rag-src/registered/.

NOTE: All .json files consumed here contain JSON payloads, not plain text.
Parse with orjson.loads() or json.loads(); do not treat as UTF-8 text.

Pipeline position: Crawler.py → ChunkSplitter.py → RagIngester.py
"""

import argparse
import dataclasses
import datetime
import shutil
import sqlite3
import time
from collections import defaultdict
from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path

import httpx
import orjson
from db.helper import SQLiteHelper
from db.models import RagConsistencyReport
from rag.exceptions import ChunkFormatError
from rag.ingestion.document_manager import DocumentManager
from rag.ingestion.pipeline_utils import read_chunk_json
from rag.models_data import ChunkDocument
from rag.utils import floats_to_blob, validate_url
from shared.config_loader import ConfigLoader
from shared.json_utils import parse_http_json
from shared.llm_client import build_embed_url
from shared.logger import Logger

logger = Logger(__name__, "/opt/llm/logs/ingest.log")

# Accepted lang values enforced by the documents.lang CHECK constraint
_VALID_LANGS: frozenset[str] = frozenset({"en", "ja"})

# ──────────────────────────────────────────────────────────────────────────────
# Type definitions
# ──────────────────────────────────────────────────────────────────────────────


class IngestionFailureReason(StrEnum):
    """Reason why a chunk ingestion failed."""

    PARSE_FAILED = "parse_failed"
    VALIDATION_FAILED = "validation_failed"
    EMBEDDING_FAILED = "embedding_failed"
    STORAGE_FAILED = "storage_failed"
    UNEXPECTED_FAILURE = "unexpected_failure"
    GROUP_VALIDATION_FAILED = "group_validation_failed"


@dataclass(frozen=True)
class PreparedChunk:
    """Immutable DTO representing a prepared chunk ready for atomic insertion."""

    doc_id: int
    chunk_index: int
    content: str
    normalized_content: str | None
    embedding_blob: bytes  # Result of floats_to_blob()
    chunk_type: str
    source_file: str


@dataclasses.dataclass(frozen=True)
class IngestUrlResult:
    """Per-URL ingestion outcome returned by ingest_url_group()."""

    url: str
    n_success: int
    n_failed: int
    skipped: bool
    n_embed_failed: int = 0  # embedding failures (separate from parse/DB failures)
    failure_reason: IngestionFailureReason | None = None


# ──────────────────────────────────────────────────────────────────────────────
# RagIngester class
# ──────────────────────────────────────────────────────────────────────────────
class RagIngester:
    """Embeds chunk files produced by ChunkSplitter and inserts them into SQLite; chunks are grouped by URL and moved to registered/ after ingestion."""

    def __init__(self, config: dict | None = None) -> None:
        """Initialize with optional config override and load ingester settings."""
        cfg: dict = config or ConfigLoader().load("ingester.toml")
        rag_src_dir = Path(cfg["rag_src_dir"])
        self._chunk_dir: Path = rag_src_dir / "chunk"
        self._registered_dir: Path = rag_src_dir / "registered"
        self._embed_url: str = build_embed_url(cfg["embed_url"])
        self._embed_retry: int = int(cfg["embed_retry"])
        self._embed_workers: int = int(cfg.get("embed_workers", 4))
        # DB settings stored explicitly to bypass build_db_config() / agent.toml
        self._rag_db_path: str = str(cfg.get("rag_db_path", ""))
        self._sqlite_vec_so: str = str(cfg.get("sqlite_vec_so", ""))
        self._sqlite_timeout: int = int(cfg.get("sqlite_timeout", 30))
        self._sqlite_busy_timeout_ms: int = int(
            cfg.get("sqlite_busy_timeout_ms", 30000)
        )
        self._rag_pipeline_service_url: str = cfg.get("rag_pipeline_service_url", "")
        self._client = httpx.Client(timeout=60)

    def close(self) -> None:
        """Close the underlying HTTP client."""
        self._client.close()

    def __del__(self) -> None:
        """Ensure the HTTP client is closed during garbage collection."""
        try:
            client = getattr(self, "_client", None)
            if client is not None:
                client.close()
        except OSError:
            pass

    # ── Public interface ──────────────────────────────────────────────────────

    def ingest_all(
        self,
        force: bool = False,
        on_ingest_complete: Callable[[], None] | None = None,
    ) -> RagConsistencyReport | None:
        """Process all chunk files in chunk_dir grouped by URL; force=True deletes existing document records before re-inserting.

        Returns the post-ingestion consistency report, or None if the check failed.
        Callers that do not inspect the return value are unaffected.
        """
        chunk_files = sorted(self._chunk_dir.glob("*.json"))
        if not chunk_files:
            logger.info("No chunk files to process")
            return None
        url_groups = self._group_chunks_by_url(chunk_files)

        consistency_report: RagConsistencyReport | None = None
        with SQLiteHelper(
            db_path=self._rag_db_path,
            sqlite_vec_so=self._sqlite_vec_so,
            sqlite_timeout=self._sqlite_timeout,
            sqlite_busy_timeout_ms=self._sqlite_busy_timeout_ms,
        ).open(write_mode=True, row_factory=True) as db:
            doc_mgr = DocumentManager(db)
            results = self._process_url_groups(doc_mgr, db, url_groups, force)
            consistency_report = doc_mgr.check_consistency(
                embed_failed=sum(
                    r.n_embed_failed for r in results if r.n_embed_failed > 0
                ),
                on_ingest_complete=on_ingest_complete,
            )

        total_success = sum(r.n_success for r in results)
        total_failed = sum(r.n_failed for r in results if r.n_failed > 0)
        total_embed_failed = sum(
            r.n_embed_failed for r in results if r.n_embed_failed > 0
        )
        total_skipped = sum(1 for r in results if r.skipped)
        logger.info(
            "=== done: %s URLs processed (%d success, %d failed, %d embed-failed, %d skipped) ===",
            len(results),
            total_success,
            total_failed,
            total_embed_failed,
            total_skipped,
            extra={"stage_name": "ingester"},
        )
        if consistency_report is None:
            logger.warning("Consistency check failed after ingestion")
        elif consistency_report.issues:
            logger.warning(
                "Ingestion completed with %d inconsistency issue(s): %s",
                len(consistency_report.issues),
                "; ".join(consistency_report.issues),
            )
        # Invalidate RAG pipeline semantic cache after ingestion (only when at least one URL group succeeded)
        if any(r.n_success > 0 for r in results) and self._rag_pipeline_service_url:
            try:
                resp = self._client.post(
                    self._rag_pipeline_service_url + "/rag_invalidate_cache"
                )
                resp.raise_for_status()
            except httpx.HTTPError as e:
                logger.warning(f"Cache invalidation failed: {e}")
        return consistency_report

    def ingest_url_group(
        self,
        doc_mgr: DocumentManager,
        db: SQLiteHelper,
        url: str,
        chunk_files: list[Path],
        force: bool,
    ) -> IngestUrlResult:
        """Ingest all chunk files for one URL into SQLite in ascending chunk_index order; routes files based on success/failure."""
        if not chunk_files:
            return self._skip_result(url)

        chunk_files = sorted(chunk_files, key=lambda p: p.stem)
        try:
            first_data = self._read_chunk_json(chunk_files[0])
        except ChunkFormatError:
            return IngestUrlResult(
                url=url, n_success=0, n_failed=len(chunk_files), skipped=False
            )

        first_fields = (
            first_data.url,
            first_data.title,
            first_data.lang,
            first_data.fetched_at,
            first_data.etag,
            first_data.last_modified,
            first_data.source_file,
            first_data.chunking_strategy,
            first_data.chunk_type,
        )
        chunk_indices: set[int] = set()
        for cp in chunk_files:
            try:
                cd = self._read_chunk_json(cp)
            except ChunkFormatError:
                return IngestUrlResult(
                    url=url, n_success=0, n_failed=len(chunk_files), skipped=False
                )
            cf = (
                cd.url,
                cd.title,
                cd.lang,
                cd.fetched_at,
                cd.etag,
                cd.last_modified,
                cd.source_file,
                cd.chunking_strategy,
                cd.chunk_type,
            )
            if cf != first_fields:
                return IngestUrlResult(
                    url=url,
                    n_success=0,
                    n_failed=len(chunk_files),
                    skipped=False,
                    failure_reason=IngestionFailureReason.GROUP_VALIDATION_FAILED,
                )
            chunk_indices.add(cd.chunk_index)
        expected = set(range(len(chunk_files)))
        if chunk_indices != expected:
            return IngestUrlResult(
                url=url,
                n_success=0,
                n_failed=len(chunk_files),
                skipped=False,
                failure_reason=IngestionFailureReason.GROUP_VALIDATION_FAILED,
            )

        title = first_data.title
        lang = first_data.lang
        etag = first_data.etag
        last_modified = first_data.last_modified
        chunking_strategy = first_data.chunking_strategy

        doc_id, skip, replace = self._get_or_create_document(
            doc_mgr,
            db,
            url,
            title,
            lang,
            force,
            etag=etag,
            last_modified=last_modified,
            chunking_strategy=chunking_strategy,
            fetched_at=first_data.fetched_at,
        )
        if skip:
            logger.info("already registered, skipping", extra={"url": url})
            self._move_to_registered(chunk_files)
            return self._skip_result(url)

        effective_doc_id = doc_id if doc_id is not None else -1

        prepared_chunks, prepared_paths, failed_paths, embed_failed = (
            self._prepare_chunks(effective_doc_id, chunk_files)
        )

        if len(prepared_chunks) > 0 and len(failed_paths) == 0:
            self._commit_url_transaction(
                doc_mgr,
                db,
                url,
                doc_id,
                prepared_chunks,
                prepared_paths,
                force,
                replace,
                title,
                lang,
                etag=etag,
                last_modified=last_modified,
                chunking_strategy=chunking_strategy,
                fetched_at=first_data.fetched_at,
            )
            self._route_chunk_files(prepared_paths, failed_paths)
        else:
            failed_all = [
                (p, "embedding_partial_failure") for p in prepared_paths
            ] + failed_paths
            self._route_chunk_files([], failed_all)

        n_success = len(prepared_chunks) if len(failed_paths) == 0 else 0

        self._log_ingestion_result(
            doc_id if doc_id is not None else -1,
            url,
            n_success,
            len(chunk_files),
            len(failed_paths),
            embed_failed,
        )
        return IngestUrlResult(
            url=url,
            n_success=n_success,
            n_failed=len(failed_paths),
            skipped=False,
            n_embed_failed=embed_failed,
        )

    # ── Embedding ─────────────────────────────────────────────────────────────

    def _get_embedding(self, text: str) -> list[float] | None:
        """Return embedding vector for text.

        Returns None on empty input or network failure.
        """
        if not text or not text.strip():
            return None
        for attempt in range(self._embed_retry):
            try:
                resp = self._client.post(
                    self._embed_url,
                    json={"content": text},
                )
                resp.raise_for_status()
                data = parse_http_json(resp)
                embedding = data.get("embedding")
                if not isinstance(embedding, list) or not embedding:
                    raise ValueError("missing or empty 'embedding' field in response")
                return embedding
            except (
                httpx.RequestError,
                httpx.HTTPStatusError,
                ValueError,
            ) as e:
                logger.warning(
                    "embedding attempt %s/%s: %s",
                    attempt + 1,
                    self._embed_retry,
                    e,
                )
                if attempt < self._embed_retry - 1:
                    time.sleep(min(2**attempt, 10))
        return None

    # ── Result helpers ────────────────────────────────────────────────────────

    @staticmethod
    def _skip_result(url: str) -> IngestUrlResult:
        """Return a skipped result for a URL."""
        return IngestUrlResult(url=url, n_success=0, n_failed=0, skipped=True)

    @staticmethod
    def _validation_failure_result(
        url: str, chunk_files: list[Path]
    ) -> IngestUrlResult:
        """Return a failure result when artifact validation fails."""
        return IngestUrlResult(
            url=url, n_success=0, n_failed=len(chunk_files), skipped=False
        )

    @staticmethod
    def _log_ingestion_result(
        doc_id: int,
        url: str,
        inserted: int,
        total: int,
        failed: int,
        embed_failed: int,
    ) -> None:
        """Log the chunk ingestion result."""
        src_type = "file" if url.startswith("file://") else "http"
        logger.info(
            "inserted %s/%s chunks (%s failed, %s embed-failed): %s",
            inserted,
            total,
            failed,
            embed_failed,
            url,
            extra={"doc_id": doc_id, "source_type": src_type, "stage_name": "ingester"},
        )

    # ── Document helpers ──────────────────────────────────────────────────────

    @staticmethod
    def _log_ingest_failure(doc_id: int, path: Path, e: Exception) -> None:
        """Log a chunk ingestion failure."""
        chunk_url = ""
        try:
            chunk_data = read_chunk_json(path)
            chunk_url = chunk_data.url or ""
        except ChunkFormatError:
            pass
        logger.error(
            "Failed to ingest %s: %s",
            path,
            e,
            extra={
                "doc_id": doc_id,
                "url": chunk_url,
                "source_type": "file",
                "stage_name": "ingester",
            },
        )

    def _validate_lang(self, lang: str) -> bool:
        """Return True when lang is a valid value."""
        return lang in _VALID_LANGS

    def _get_or_create_document(
        self,
        doc_mgr: DocumentManager,
        db: SQLiteHelper,
        url: str,
        title: str,
        lang: str,
        force: bool,
        *,
        etag: str | None = None,
        last_modified: str | None = None,
        chunking_strategy: str = "text",
        fetched_at: str,
    ) -> tuple[int | None, bool, bool]:
        """Register a URL in documents and return its doc_id and whether replacement is needed.
        Returns (None, True) if already registered and skip=True.
        """
        if not self._validate_lang(lang):
            raise ValueError(
                f"unsupported lang value: {lang!r} (must be one of {sorted(_VALID_LANGS)})",
            )
        existing_row = db.execute(
            "SELECT doc_id FROM documents WHERE url = ?",
            (url,),
        ).fetchone()
        if existing_row:
            existing_doc_id: int = existing_row[0]
            doc_id, skip, replace = doc_mgr.handle_existing_document(
                url,
                existing_doc_id,
                force,
                etag,
                last_modified,
                fetched_at,
                lambda u: u.startswith("file://"),
            )
            if skip:
                return None, True, False
            if replace:
                return existing_doc_id, False, True
            return existing_doc_id, False, False
        return None, False, False

    def _insert_document(
        self,
        db: SQLiteHelper,
        url: str,
        title: str,
        lang: str,
        etag: str | None,
        last_modified: str | None,
        chunking_strategy: str,
        fetched_at: str,
    ) -> sqlite3.Cursor:
        """Insert a document row and return the cursor."""
        cursor: sqlite3.Cursor = db.execute(
            "INSERT INTO documents"
            " (url, title, lang, etag, last_modified, chunking_strategy, fetched_at)"
            " VALUES (?, ?, ?, ?, ?, ?, ?)",
            (url, title, lang, etag, last_modified, chunking_strategy, fetched_at),
        )
        return cursor

    def _insert_chunk(
        self,
        db: SQLiteHelper,
        doc_id: int,
        idx: int,
        content: str,
        normalized_content: str | None,
        embedding: list[float],
        chunk_type: str = "",
        source_file: str = "",
    ) -> None:
        """Insert a chunk and its embedding vector; chunks_fts synced via trigger using COALESCE(normalized_content, content); embedding stored as float32 BLOB."""
        cur = db.execute(
            "INSERT INTO chunks (doc_id, chunk_index, content, normalized_content, chunk_type, source_file)"
            " VALUES (?, ?, ?, ?, ?, ?)",
            (doc_id, idx, content, normalized_content or None, chunk_type, source_file),
        )
        chunk_id = cur.lastrowid
        db.execute(
            "INSERT INTO chunks_vec (chunk_id, embedding) VALUES (?, ?)",
            (chunk_id, floats_to_blob(embedding)),
        )

    def _insert_chunks_batch(
        self,
        db: SQLiteHelper,
        prepared_chunks: list[PreparedChunk],
    ) -> int:
        """Insert multiple prepared chunks atomically within a single transaction. Returns the number of inserted chunks."""
        n = len(prepared_chunks)
        if n == 0:
            return 0
        inserted = 0
        for pc in prepared_chunks:
            cur = db.execute(
                "INSERT INTO chunks (doc_id, chunk_index, content, normalized_content, chunk_type, source_file)"
                " VALUES (?, ?, ?, ?, ?, ?)",
                (
                    pc.doc_id,
                    pc.chunk_index,
                    pc.content,
                    pc.normalized_content or None,
                    pc.chunk_type,
                    pc.source_file,
                ),
            )
            chunk_id = cur.lastrowid
            db.execute(
                "INSERT INTO chunks_vec (chunk_id, embedding) VALUES (?, ?)",
                (chunk_id, pc.embedding_blob),
            )
            inserted += 1
        return inserted

    # ── Bulk file processing ──────────────────────────────────────────────────

    def _read_chunk_json(self, path: Path) -> ChunkDocument:
        """Read and validate a chunk JSON file; returns ChunkDocument.

        Raises ChunkFormatError on any validation failure.
        """
        return read_chunk_json(path)

    def _embed_and_store(
        self, doc_id: int, path: Path
    ) -> PreparedChunk | IngestionFailureReason:
        """Embed one chunk without DB access; returns a PreparedChunk ready for atomic insertion or a failure reason."""
        try:
            data = self._read_chunk_json(path)
        except ChunkFormatError:
            return IngestionFailureReason.PARSE_FAILED
        content: str = data.content
        nc_raw = data.normalized_content
        normalized_content: str | None = (
            nc_raw if isinstance(nc_raw, str) and nc_raw else None
        )
        idx = data.chunk_index
        chunk_type: str = data.chunk_type or ""
        source_file: str = data.source_file or ""
        # Embed original content; E5 understands raw Japanese.
        # normalized_content is for FTS only and not used for embedding.
        embedding = self._get_embedding(content)
        if embedding is None:
            chunk_url = data.url
            logger.warning(
                "embedding failed for %s: %r",
                path.name,
                content[:60],
                extra={
                    "doc_id": doc_id,
                    "url": chunk_url,
                    "source_type": "file",
                    "stage_name": "ingester",
                },
            )
            return IngestionFailureReason.EMBEDDING_FAILED
        return PreparedChunk(
            doc_id=doc_id,
            chunk_index=idx,
            content=content,
            normalized_content=normalized_content,
            embedding_blob=floats_to_blob(embedding),
            chunk_type=chunk_type,
            source_file=source_file,
        )

    def _prepare_chunks(
        self, doc_id: int, chunk_files: list[Path]
    ) -> tuple[list[PreparedChunk], list[Path], list[tuple[Path, str]], int]:
        """Embed chunk files in parallel via ThreadPoolExecutor; returns (prepared_chunks, prepared_paths, failed_paths_with_reasons, embed_failed_count)."""
        prepared_chunks: list[PreparedChunk] = []
        prepared_paths: list[Path] = []
        failed_paths: list[tuple[Path, str]] = []
        embed_failed = 0
        with ThreadPoolExecutor(max_workers=self._embed_workers) as executor:
            futures = {
                executor.submit(self._embed_and_store, doc_id, path): path
                for path in chunk_files
            }
            for future in as_completed(futures):
                path = futures[future]
                try:
                    result = future.result()
                    if isinstance(result, PreparedChunk):
                        prepared_chunks.append(result)
                        prepared_paths.append(path)
                    elif isinstance(result, IngestionFailureReason):
                        reason_str = (
                            result.value if hasattr(result, "value") else str(result)
                        )
                        if "embedding" in reason_str.lower():
                            embed_failed += 1
                        failed_paths.append((path, reason_str))
                    else:
                        failed_paths.append(
                            (path, f"unexpected result type: {type(result).__name__}")
                        )
                except (
                    httpx.HTTPStatusError,
                    httpx.RequestError,
                    OSError,
                    ValueError,
                    TypeError,
                ) as e:
                    self._log_ingest_failure(doc_id, path, e)
                    failed_paths.append((path, str(e)))
        return prepared_chunks, prepared_paths, failed_paths, embed_failed

    def _commit_url_transaction(
        self,
        doc_mgr: DocumentManager,
        db: SQLiteHelper,
        url: str,
        doc_id: int | None,
        prepared_chunks: list[PreparedChunk],
        prepared_paths: list[Path],
        force: bool,
        replace: bool,
        title: str,
        lang: str,
        *,
        etag: str | None,
        last_modified: str | None,
        chunking_strategy: str,
        fetched_at: str,
    ) -> None:
        """Atomically commit all database changes for a URL inside BEGIN IMMEDIATE transaction."""
        with db.begin_immediate():
            if doc_id is None or replace:
                if replace and doc_id is not None:
                    doc_mgr.delete_existing_document(doc_id)
                cursor = self._insert_document(
                    db,
                    url,
                    title,
                    lang,
                    etag,
                    last_modified,
                    chunking_strategy,
                    fetched_at,
                )
                if cursor.lastrowid is None:
                    raise RuntimeError("Failed to retrieve lastrowid after insertion")
                new_doc_id: int = cursor.lastrowid
                prepared_chunks = [
                    dataclasses.replace(pc, doc_id=new_doc_id) for pc in prepared_chunks
                ]
                doc_id = new_doc_id

            # Now insert the prepared chunks using the (possibly new/updated) doc_id
            self._insert_chunks_batch(db, prepared_chunks)

        # Commit succeeded — move files to registered/
        self._move_to_registered(prepared_paths)

    def _group_chunks_by_url(self, chunk_files: list[Path]) -> dict[str, list[Path]]:
        """Group chunk files by URL read from their JSON 'url' field."""
        url_groups: dict[str, list[Path]] = defaultdict(list)
        for path in chunk_files:
            try:
                data = self._read_chunk_json(path)
            except ChunkFormatError:
                continue
            url: str = data.url or ""
            if not url:
                logger.warning(
                    "url field missing: %s",
                    path.name,
                    extra={"source_type": "file", "stage_name": "ingester"},
                )
                continue
            # Accept file:// URLs from local file ingestion in addition to http/https
            if not validate_url(url) and not url.startswith("file://"):
                logger.warning(
                    "invalid url %r in %s, skipping",
                    url,
                    path.name,
                    extra={"source_type": "file", "stage_name": "ingester"},
                )
                continue
            url_groups[url].append(path)
        return url_groups

    def _process_url_groups(
        self,
        doc_mgr: DocumentManager,
        db: SQLiteHelper,
        url_groups: dict[str, list[Path]],
        force: bool,
    ) -> list[IngestUrlResult]:
        """Iterate over URL groups and ingest each; log exceptions without stopping."""
        results: list[IngestUrlResult] = []
        for url, paths in url_groups.items():
            try:
                results.append(self.ingest_url_group(doc_mgr, db, url, paths, force))
            except (
                OSError,
                RuntimeError,
                ValueError,
                sqlite3.OperationalError,
                sqlite3.IntegrityError,
            ):
                logger.exception("ingest_url_group failed: %s", url)
                results.append(
                    IngestUrlResult(
                        url=url,
                        n_success=0,
                        n_failed=0,
                        skipped=False,
                        failure_reason=IngestionFailureReason.UNEXPECTED_FAILURE,
                    )
                )
        return results

    def _move_to_registered(self, paths: list[Path]) -> None:
        """Move ingested chunk files to registered/."""
        self._registered_dir.mkdir(parents=True, exist_ok=True)
        for path in paths:
            dest = self._registered_dir / path.name
            try:
                shutil.move(str(path), str(dest))
            except OSError as e:
                chunk_url = ""
                try:
                    chunk_data = self._read_chunk_json(path)
                    chunk_url = chunk_data.url or ""
                except ChunkFormatError:
                    pass
                logger.error(
                    "move failed %s → %s: %s",
                    path,
                    dest,
                    e,
                    extra={
                        "url": chunk_url,
                        "source_type": "file",
                        "stage_name": "ingester",
                    },
                )

    def _route_chunk_files(
        self, successful_paths: list[Path], failed_paths: list[tuple[Path, str]]
    ) -> None:
        """Route chunk files based on success/failure: successful→registered/, failed→retry/ or failed/."""
        self._registered_dir.mkdir(parents=True, exist_ok=True)
        retry_dir = self._chunk_dir.parent / "retry"
        retry_dir.mkdir(parents=True, exist_ok=True)
        failed_dir = self._chunk_dir.parent / "failed"
        failed_dir.mkdir(parents=True, exist_ok=True)

        for path in successful_paths:
            dest = self._registered_dir / path.name
            try:
                shutil.move(str(path), str(dest))
            except OSError as e:
                chunk_url = ""
                try:
                    chunk_data = self._read_chunk_json(path)
                    chunk_url = chunk_data.url or ""
                except ChunkFormatError:
                    pass
                logger.error(
                    "move failed %s → %s: %s",
                    path,
                    dest,
                    e,
                    extra={
                        "url": chunk_url,
                        "source_type": "file",
                        "stage_name": "ingester",
                    },
                )

        for path, reason in failed_paths:
            error_metadata = self._write_error_metadata(path, reason)
            if error_metadata is not None:
                error_path = failed_dir / f"{path.stem}.error.json"
                try:
                    error_path.write_bytes(orjson.dumps(error_metadata))
                except OSError as e:
                    logger.warning(
                        "Failed to write .error.json metadata for %s: %s",
                        path,
                        e,
                        extra={"stage_name": "ingester"},
                    )

            if "embedding" in reason.lower():
                dest = retry_dir / path.name
            else:
                dest = failed_dir / path.name
            try:
                shutil.move(str(path), str(dest))
            except OSError as e:
                logger.warning(
                    "Failed to move failed chunk %s → %s: %s",
                    path,
                    dest,
                    e,
                    extra={"stage_name": "ingester"},
                )

    def _write_error_metadata(self, path: Path, failure_reason: str) -> dict | None:
        """Write .error.json metadata for a failed chunk."""
        try:
            chunk_data = self._read_chunk_json(path)
        except ChunkFormatError:
            return None

        metadata = {
            "schema_version": "1",
            "created_by": "rag_ingester",
            "failure_reason": failure_reason,
            "timestamp": datetime.datetime.now(datetime.UTC).isoformat(),
        }

        url = chunk_data.url or ""
        if url:
            metadata["url"] = url

        chunk_index_raw = chunk_data.chunk_index
        if chunk_index_raw is not None:
            metadata["chunk_index"] = str(chunk_index_raw)

        source_file = chunk_data.source_file or ""
        if source_file:
            metadata["source_file"] = source_file

        return metadata


