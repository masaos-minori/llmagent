#!/usr/bin/env python3
"""scripts/rag/ingestion/chunk_splitter.py

Reads rag-src/*.json (JSON files generated by crawler), splits text and code
into chunks, and saves them to rag-src/chunk/{stem}-{idx:04d}.json.

NOTE: All .json files (input and output) contain JSON payloads, not plain text.
Output file format: JSON
  {url, title, lang, source_file, chunk_index, chunk_type, content}
  chunk_type: "text" or "code"

Pipeline position: crawler → chunk_splitter → ingester
"""

import argparse
import logging
import os
import re
import sys
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal, TypedDict

import orjson
from shared.config_loader import ConfigLoader
from shared.logger import Logger
from shared.runtime_paths import resolve_sudachi_dict_path
from sudachipy import dictionary as sudachi_dict

from rag.exceptions import (
    ChunkFormatError,
    IngestionFailureReason,
    PipelineValidationError,
)
from rag.ingestion.chunk_english import ChunkEnglishMixin
from rag.ingestion.chunk_japanese import ChunkJapaneseMixin, Tokenizer
from rag.ingestion.chunk_utils import merge_text_items
from rag.ingestion.pipeline_utils import (
    collect_source_files,
    is_already_processed,
    read_crawl_json,
)
from rag.models_data import ChunkDocument, ChunkSettings
from rag.utils import normalize_unicode

# NOTE: unvalidated heuristic, pending performance tuning
MIN_HEADING_LINES_FOR_MARKDOWN = 2
MARKDOWN_HEADING_RE = r"^#{1,6}"

logger = Logger(__name__, "/opt/llm/logs/chunk.log", structured_log=True)


@dataclass
class FileOutcome:
    """Per-file result of a chunk run: processed, skipped, or failed.

    ``chunk_count`` carries the number of chunks written for a processed file;
    ``reason`` carries the mapped ``IngestionFailureReason`` for a failed file.
    """

    path: Path
    status: Literal["processed", "skipped", "failed"]
    chunk_count: int = 0
    reason: IngestionFailureReason | None = None


@dataclass
class ChunkRunResult:
    """Aggregate chunk-run outcome: processed/skipped/failed counts and per-file reasons."""

    processed: int = 0
    skipped: int = 0
    failed: int = 0
    failures: dict[Path, IngestionFailureReason] = field(default_factory=dict)


def _map_failure_class(exc: BaseException) -> IngestionFailureReason:
    """Map a raised exception to its chunk-stage ``IngestionFailureReason``.

    The failure-bearing paths map to their dedicated reason; ``TokenizationError``
    and any other exception fall back to ``UNEXPECTED_FAILURE``.
    """
    if isinstance(exc, OSError):
        return IngestionFailureReason.STORAGE_FAILED
    if isinstance(exc, ChunkFormatError):
        return IngestionFailureReason.PARSE_FAILED
    if isinstance(exc, PipelineValidationError):
        return IngestionFailureReason.VALIDATION_FAILED
    return IngestionFailureReason.UNEXPECTED_FAILURE


class ChunkMetadata(TypedDict, total=False):
    """Typed dict for document-level metadata shared across chunk files.

    All fields are optional because this dict is spread with ** into the output payload.
    TypedDict spreading requires total=False and cannot be used in constructor calls.
    """

    url: str
    title: str
    lang: str
    fetched_at: str
    etag: str | None
    last_modified: str | None
    source_file: str
    chunking_strategy: str


def _require_int(cfg: dict, key: str, *, default: int | None = None) -> int:
    """Return ``cfg[key]`` as an int, rejecting bool/float/str with PipelineValidationError.

    Falls back to ``default`` when the key is absent. A non-int ``default`` is a
    code error, not a config error, so the literal default is assumed to be an int.
    A ``bool`` is rejected explicitly because it subclasses ``int``.
    """
    raw = cfg[key] if key in cfg else default
    if isinstance(raw, bool) or not isinstance(raw, int):
        raise PipelineValidationError(f"{key} must be an integer, got {raw!r}")
    return raw


# ──────────────────────────────────────────────────────────────────────────────
# ChunkSplitter class
# ──────────────────────────────────────────────────────────────────────────────
class ChunkSplitter(ChunkEnglishMixin, ChunkJapaneseMixin):
    """Splits crawl output (rag-src/*.json JSON) into text and code chunks and writes them to rag-src/chunk/ for ingestion."""

    def __init__(self, config: dict | None = None) -> None:
        """Initialize the chunk splitter with configuration from TOML file or provided dict."""
        cfg: dict = config or ConfigLoader().load("chunk_splitter.toml")
        rag_src_dir = Path(cfg["rag_src_dir"])
        self._chunk_dir: Path = rag_src_dir / "chunk"
        self._rag_src_dir: Path = rag_src_dir

        # Chunk-size group validation + typed getters, before Sudachi construction.
        min_chunk = _require_int(cfg, "min_chunk")
        max_chunk = _require_int(cfg, "max_chunk")
        chunk_overlap = _require_int(cfg, "chunk_overlap", default=50)

        if min_chunk < 0:
            raise PipelineValidationError(f"min_chunk must be >= 0, got {min_chunk}")
        if min_chunk > max_chunk:
            raise PipelineValidationError(
                f"min_chunk ({min_chunk}) must be <= max_chunk ({max_chunk})"
            )
        if chunk_overlap < 0:
            raise PipelineValidationError(
                f"chunk_overlap must be >= 0, got {chunk_overlap}"
            )
        if chunk_overlap >= max_chunk:
            raise PipelineValidationError(
                f"chunk_overlap ({chunk_overlap}) must be < max_chunk ({max_chunk})"
            )

        en_stopwords = frozenset(cfg["en_stopwords"])
        ja_stop_pos = frozenset(cfg["ja_stop_pos"])

        md_index_enable = cfg.get("md_index_enable", False)
        if not isinstance(md_index_enable, bool):
            raise PipelineValidationError(
                f"md_index_enable must be a boolean, got {md_index_enable!r}"
            )
        # Read once; range-check only when the feature is enabled (REQ-004).
        md_snippet_max_chars = _require_int(cfg, "md_snippet_max_chars", default=600)
        if md_index_enable and not (min_chunk <= md_snippet_max_chars <= max_chunk):
            raise PipelineValidationError(
                f"md_snippet_max_chars ({md_snippet_max_chars}) must be within "
                f"[min_chunk={min_chunk}, max_chunk={max_chunk}]"
            )

        # Aggregate the validated settings into one immutable value object so the
        # chunk mixins read a single collaborator instead of scattered host
        # attributes (ragcrv006, REQ-001). Built once before the Sudachi build.
        self._settings = ChunkSettings(
            min_chunk=min_chunk,
            max_chunk=max_chunk,
            chunk_overlap=chunk_overlap,
            md_snippet_max_chars=md_snippet_max_chars,
            md_index_enable=md_index_enable,
            en_stopwords=en_stopwords,
            ja_stop_pos=ja_stop_pos,
        )

        # SplitMode.C: longest compound unit; optimal for NLP downstream tasks.
        # Stored behind the local Tokenizer Protocol so no Any leaks into the path.
        sd_dict = sudachi_dict.Dictionary(dict=resolve_sudachi_dict_path())
        self._tokenizer: Tokenizer = sd_dict.create()

    # ── Public interface ──────────────────────────────────────────────────────

    def _iter_file_outcomes(
        self, paths: list[Path], force: bool = False
    ) -> Iterator[FileOutcome]:
        """Yield one :class:`FileOutcome` per path, never raising out of the loop.

        Each file is classified ``processed`` (>=1 chunk written), ``skipped``
        (returned 0 legitimately), or ``failed`` (exception raised); on failure the
        exception is mapped to an ``IngestionFailureReason`` and logged once.
        """
        for path in paths:
            try:
                count = self.process_file(path, force)
            except Exception as e:
                logger.exception("process_file failed: %s: %s", path, e)
                yield FileOutcome(path, "failed", reason=_map_failure_class(e))
                continue
            if count > 0:
                yield FileOutcome(path, "processed", chunk_count=count)
            else:
                yield FileOutcome(path, "skipped")

    def process_all(self, target: Path | None = None, force: bool = False) -> int:
        """Process all *.json files in rag-src/ (or a single target); returns total chunks written."""
        paths = self._collect_targets(target)
        if not paths:
            logger.info("No source files to process")
            return 0
        total = 0
        for outcome in self._iter_file_outcomes(paths, force):
            if outcome.status == "processed":
                total += outcome.chunk_count
        logger.info("=== done: %s chunks from %s files ===", total, len(paths))
        return total

    def run_all(
        self, target: Path | None = None, force: bool = False
    ) -> ChunkRunResult:
        """Run the chunk stage over all targets; returns the per-file outcome aggregate.

        Consumes the same iterator as :meth:`process_all` so the two entry points
        cannot diverge. Logs a run-level summary line.
        """
        paths = self._collect_targets(target)
        result = ChunkRunResult()
        for outcome in self._iter_file_outcomes(paths, force):
            if outcome.status == "processed":
                result.processed += 1
            elif outcome.status == "skipped":
                result.skipped += 1
            else:
                result.failed += 1
                assert outcome.reason is not None  # guarded by _iter_file_outcomes
                result.failures[outcome.path] = outcome.reason
        logger.info(
            "=== run done: %d processed, %d skipped, %d failed ===",
            result.processed,
            result.skipped,
            result.failed,
        )
        return result

    def process_file(self, src_path: Path, force: bool = False) -> int:
        """Read a crawler JSON file, split into chunks, and write to chunk_dir; returns chunk count; skips already-chunked files when force=False."""
        if not src_path.exists():
            logger.error("Source file does not exist: %s", src_path)
            return 0
        sentinel = self._chunk_dir / f"{src_path.stem}-0000.json"
        if is_already_processed(sentinel, force):
            chunk_doc = self._read_source_data(src_path)
            if chunk_doc is not None:
                logger.info(
                    "skip (already chunked)",
                    extra={"url": chunk_doc.url},
                )
            return 0
        self._clear_leftover_temp_files(src_path.stem)
        chunk_doc = self._read_source_data(src_path)
        if chunk_doc is None:
            return 0
        chunks = self._build_chunk_list(chunk_doc)
        chunking_strategy = "heading" if self._is_markdown_source(chunk_doc) else "text"
        if force:
            self._prune_stale_chunk_files(src_path.stem)
        written = self._write_chunk_files(
            chunks, chunk_doc, src_path, chunking_strategy
        )
        logger.info(
            "chunked %s chunks from %s",
            written,
            src_path.name,
            extra={"url": chunk_doc.url},
        )
        if self._discarded_count > 0:
            _discard_level = logging.WARNING if written == 0 else logging.INFO
            logger.log(
                _discard_level,
                "discarded %s item(s) (%s chars) below min_chunk",
                self._discarded_count,
                self._discarded_chars,
                extra={
                    "url": chunk_doc.url,
                    "source_type": "file",
                    "stage_name": "chunk",
                    "discard_reason": "below_min_chunk",
                    "discarded_count": self._discarded_count,
                    "discarded_chars": self._discarded_chars,
                },
            )
        return written

    def _prune_stale_chunk_files(self, stem: str) -> int:
        """Delete existing chunk files matching {stem}-{NNNN}.json; returns the number removed.

        Called on forced runs so the new series is authoritative: obsolete chunks of
        a previous (longer) run must not survive and be re-ingested with fresh ones.
        A failure to remove one file is logged and does not stop the run.
        """
        if not self._chunk_dir.exists():
            return 0
        pattern = re.compile(rf"^{re.escape(stem)}-\d{{4,}}\.json$")
        removed: int = 0
        for path in self._chunk_dir.iterdir():
            if not path.is_file() or not pattern.fullmatch(path.name):
                continue
            try:
                path.unlink()
                removed += 1
            except OSError as e:
                logger.error("failed to remove stale chunk %s: %s", path, e)
        if removed:
            logger.info("pruned %s stale chunk files for %s", removed, stem)
        return removed

    def _clear_leftover_temp_files(self, stem: str) -> None:
        """Remove leftover {stem}-*.json.tmp files from an interrupted earlier run.

        Called before writing so a crash in a previous run never leaves temp files
        that would otherwise be ingested or confuse the next run. A failure to
        remove one file is logged and does not stop the run.
        """
        if not self._chunk_dir.exists():
            return
        for path in self._chunk_dir.glob(f"{stem}-*.json.tmp"):
            try:
                path.unlink()
            except OSError as e:
                logger.error("failed to remove leftover temp chunk %s: %s", path, e)

    # ── English and Japanese chunking ─────────────────────────────────────────
    # Provided by ChunkEnglishMixin and ChunkJapaneseMixin respectively.
    # ─────────────────────────────────────────────────────────────────────────

    # ── Markdown heading chunking ──────────────────────────────────────────────

    def _is_markdown_source(self, data: ChunkDocument) -> bool:
        """Return True when the source should use heading-based snippet chunking.

        .md / .markdown / .mdx files always use heading chunking regardless of md_index_enable.
        Non-.md files use heuristic detection only when md_index_enable is set.
        """
        url = data.url
        if not isinstance(url, str):
            return False
        if url.endswith((".md", ".markdown", ".mdx")):
            return True
        if not self._settings.md_index_enable:
            return False
        content = data.content
        if not isinstance(content, str):
            return False
        return (
            len(re.findall(rf"{MARKDOWN_HEADING_RE} .+", content, re.MULTILINE))
            >= MIN_HEADING_LINES_FOR_MARKDOWN
        )

    def _chunk_markdown_by_heading(
        self, text: str, lang: str
    ) -> list[tuple[str, str | None]]:
        """Split Markdown text at heading boundaries into (content, normalized) pairs; oversized sections are segmented by the language-appropriate chunker (_chunk_japanese for lang 'ja', else _chunk_english)."""
        # Split before each heading line; keep the heading with its section
        sections = re.split(
            rf"(?={MARKDOWN_HEADING_RE} )", text.strip(), flags=re.MULTILINE
        )
        pairs: list[tuple[str, str | None]] = []
        for section in sections:
            section = section.strip()
            if not section:
                continue
            if len(section) <= self._settings.md_snippet_max_chars:
                if len(section) >= self._settings.min_chunk:
                    normalized: str | None = ""
                    if lang == "ja":
                        prepared = re.sub(
                            r"\n{3,}", "\n\n", normalize_unicode(section)
                        ).strip()
                        normalized = self._normalize_ja_sentence(prepared) or None
                    pairs.append((section, normalized))
                else:
                    # Within the snippet cap but below min_chunk: size-rule discard.
                    self._discarded_count += 1
                    self._discarded_chars += len(section)
            else:
                # Section too large; fall back to language-appropriate chunking
                if lang == "ja":
                    pairs.extend(self._chunk_japanese(section))
                else:
                    pairs.extend((c, "") for c in self._chunk_english(section))
        return pairs

    # ── Code chunking ─────────────────────────────────────────────────────────

    def _chunk_code(self, code: str) -> list[str]:
        """Split a code block at blank lines (function/class boundaries); not subject to stopword removal or morphological analysis."""
        blocks = re.split(r"\n{2,}", code.strip())
        chunks: list[str] = merge_text_items(
            blocks,
            "\n\n",
            self._settings.min_chunk,
            self._settings.max_chunk,
            self._settings.chunk_overlap,
        )
        # Measure size-rule discard by character difference. Merging only inserts
        # the separator (net-negative diff), so a positive diff means characters
        # were dropped below min_chunk. The character total is exact; the item
        # count is a best-effort approximation (see _approx_discarded_block_count).
        diff = sum(len(b) for b in blocks) - sum(len(c) for c in chunks)
        if diff > 0:
            self._discarded_chars += diff
            self._discarded_count += self._approx_discarded_block_count(blocks, chunks)
        return chunks

    def _approx_discarded_block_count(
        self, blocks: list[str], chunks: list[str]
    ) -> int:
        """Best-effort count of input blocks whose stripped text did not survive into the output.

        A block counts as discarded when its non-empty stripped text is not a
        substring of the concatenated output chunks. Approximate by design: merging
        can embed part of a block inside a larger chunk without an exact match, so
        this over-counts slightly. The character total (discarded_chars) is exact;
        this only estimates the discarded item count.
        """
        joined = "".join(chunks)
        discarded = 0
        for block in blocks:
            stripped = block.strip()
            if stripped and stripped not in joined:
                discarded += 1
        return discarded

    # ── File I/O ──────────────────────────────────────────────────────────────

    def _read_source_data(self, src_path: Path) -> ChunkDocument | None:
        """Read and parse a JSON crawl file; returns ChunkDocument or None on failure."""
        try:
            return read_crawl_json(src_path)
        except (FileNotFoundError, ChunkFormatError) as e:
            logger.error("skip %s: %s", src_path.name, e)
            return None

    def _build_chunk_list(
        self, data: ChunkDocument
    ) -> list[tuple[str, str, str | None]]:
        """Extract content from a crawl record and split into (chunk_type, content, normalized_content) triples; normalized populated only for Japanese text."""
        lang = data.lang
        # Reset the per-file size-rule discard accumulator before the fan-out so
        # text + code discard from this one source file aggregate into one total.
        self._discarded_count = 0
        self._discarded_chars = 0
        content = data.content
        code_blocks = data.code_blocks

        text_triples: list[tuple[str, str, str | None]] = self._build_text_triples(
            data, lang, content
        )
        code_triples: list[tuple[str, str, str]] = self._build_code_triples(code_blocks)

        return text_triples + code_triples

    def _build_text_triples(
        self, data: ChunkDocument, lang: str, content: str
    ) -> list[tuple[str, str, str | None]]:
        """Build text triples from content; delegates to markdown/English/Japanese chunkers."""
        if not content:
            return []
        if self._is_markdown_source(data):
            return [
                ("text", c, n)
                for c, n in self._chunk_markdown_by_heading(content, lang)
            ]
        if lang == "ja":
            return [
                ("text", orig, norm) for orig, norm in self._chunk_japanese(content)
            ]
        return [("text", c, "") for c in self._chunk_english(content)]

    def _build_code_triples(self, code_blocks: list[str]) -> list[tuple[str, str, str]]:
        """Build code triples from each code block independently."""
        return [("code", c, "") for cb in code_blocks for c in self._chunk_code(cb)]

    def _write_chunk_files(
        self,
        chunks: list[tuple[str, str, str | None]],
        data: ChunkDocument,
        src_path: Path,
        chunking_strategy: str = "text",
    ) -> int:
        """Write (chunk_type, content, normalized_content) triples to chunk_dir.

        Every chunk is first written under a temporary name; the final names are
        then published with os.replace in descending index order so the -0000
        sentinel appears last. On any OSError this run's temp and published files
        are removed and the error is re-raised so process_all logs one error.
        """
        if not chunks:
            return 0
        self._chunk_dir.mkdir(parents=True, exist_ok=True)
        metadata = self._extract_chunk_metadata(data, src_path, chunking_strategy)
        pairs: list[tuple[Path, Path]] = []
        try:
            for idx, (chunk_type, chunk_content, norm_content) in enumerate(chunks):
                final_path = self._chunk_dir / f"{src_path.stem}-{idx:04d}.json"
                temp_path = final_path.with_name(final_path.name + ".tmp")
                payload = self._build_chunk_payload(
                    metadata, idx, chunk_type, chunk_content, norm_content
                )
                temp_path.write_bytes(
                    orjson.dumps(payload, option=orjson.OPT_INDENT_2),
                )
                pairs.append((temp_path, final_path))
            return self.publish_chunk_files(pairs)
        except OSError:
            self.cleanup_chunk_files(pairs)
            raise

    def publish_chunk_files(self, pairs: list[tuple[Path, Path]]) -> int:
        """Publish (temp_path, final_path) pairs via os.replace in descending index order.

        The -0000 sentinel is published last so its presence marks a complete set.
        Returns the number of files published.
        """
        published: list[Path] = []
        for temp_path, final_path in sorted(
            pairs, key=lambda pair: pair[1].name, reverse=True
        ):
            os.replace(temp_path, final_path)
            published.append(final_path)
        return len(published)

    def cleanup_chunk_files(self, pairs: list[tuple[Path, Path]]) -> None:
        """Remove this run's temp files and any final files published in this call.

        Called from a single OSError handler around the write and publish phases so
        a failure leaves no partial or temporary output for this document.
        """
        for temp_path, final_path in pairs:
            temp_path.unlink(missing_ok=True)
            final_path.unlink(missing_ok=True)

    def _extract_chunk_metadata(
        self, data: ChunkDocument, src_path: Path, chunking_strategy: str
    ) -> ChunkMetadata:
        """Extract document-level metadata shared across all chunk files."""
        return {
            "url": data.url,
            "title": data.title,
            "lang": data.lang,
            "fetched_at": data.fetched_at,
            "etag": data.etag,
            "last_modified": data.last_modified,
            "source_file": src_path.name,
            "chunking_strategy": chunking_strategy,
        }

    def _build_chunk_payload(
        self,
        metadata: ChunkMetadata,
        idx: int,
        chunk_type: str,
        chunk_content: str,
        norm_content: str | None,
    ) -> dict[str, object]:
        """Build a single chunk JSON payload from shared metadata and chunk-specific fields."""
        return {
            "schema_version": "1",
            "artifact_type": "chunk",
            "created_by": "chunk_splitter",
            **metadata,
            "chunk_index": idx,
            "chunk_type": chunk_type,
            "content": chunk_content,
            "normalized_content": norm_content or None,
            "code_blocks": [],
        }

    def _collect_targets(self, target: Path | None) -> list[Path]:
        """Return source files to process. Delegates to pipeline_utils."""
        files, _ = collect_source_files(self._rag_src_dir, target)
        result: list[Path] = files
        return result


# ──────────────────────────────────────────────────────────────────────────────
# Entry point
# ──────────────────────────────────────────────────────────────────────────────
def main() -> int:
    """CLI entry point for chunking rag-src JSON files into document chunks."""
    parser = argparse.ArgumentParser(
        description="Chunking: rag-src/*.json → rag-src/chunk/{stem}-{idx:04d}.json",
    )
    parser.add_argument(
        "--file",
        help="Process a single file (default: process all files in rag-src/*.json)",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Re-process even if output chunks already exist",
    )
    args = parser.parse_args()

    target: Path | None = None
    if args.file:
        target = Path(args.file)
        if not target.exists():
            parser.error(f"File does not exist: {target}")

    splitter = ChunkSplitter()
    result = splitter.run_all(target, args.force)
    return 1 if result.failed > 0 else 0


if __name__ == "__main__":
    ConfigLoader.restrict_to("chunk_splitter.toml")
    sys.exit(main())
